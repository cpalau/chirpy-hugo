#!/usr/bin/env node
/**
 * Vendor the browser libraries Chirpy loads from CDNs.
 *
 *   node scripts/vendor.mjs --fetch      # clone the pinned vendor repository
 *   node scripts/vendor.mjs --apply      # copy the files into static/assets/lib
 *   node scripts/vendor.mjs --check      # verify the committed copies
 *   node scripts/vendor.mjs --generate   # rewrite tests/contract/vendor-hashes.json
 *
 * The files come from `cotes2020/chirpy-static-assets`, the repository the
 * upstream theme references in `_data/origin/basic.yml`, at a pinned commit.
 * They are copied byte for byte; the theme never edits them.
 *
 * MathJax and Mermaid are deliberately excluded: together they are ~23 MB and
 * only load on pages that need them, so those two keep the CDN. Everything on
 * the critical path of a normal page (fonts, icons, search, TOC, dates, code
 * copy, lightbox) is served from this origin.
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const CACHE = path.join(ROOT, '.out/upstream/chirpy-static-assets');
const TARGET = path.join(ROOT, 'static/assets/lib');
const MANIFEST = path.join(ROOT, 'tests/contract/vendor-hashes.json');
const REPO = 'https://github.com/cotes2020/chirpy-static-assets.git';

// Pinned to the same upstream release the theme syncs from. Bump it when the
// upstream theme bumps its vendor versions.
const PIN = '5cde3f0076b62e45fc68291893cf7d93e122adb7';

const DIRECTORIES = [
  'fonts',
  'fontawesome-free',
  'tocbot',
  'simple-jekyll-search',
  'dayjs',
  'glightbox',
  'clipboard',
  'loading-attribute-polyfill',
];

const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

async function walk(dir, prefix = '') {
  const out = [];
  for (const entry of await fsp.readdir(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), rel)));
    else out.push(rel);
  }
  return out;
}

async function files() {
  const out = [];
  for (const dir of DIRECTORIES) {
    const root = path.join(CACHE, dir);
    if (!fs.existsSync(root)) {
      throw new Error(`missing ${dir} in ${CACHE}; run with --fetch first`);
    }
    for (const rel of await walk(root)) out.push([`${dir}/${rel}`, path.join(root, rel)]);
  }
  return out.sort(([a], [b]) => a.localeCompare(b));
}

async function fetchUpstream() {
  if (fs.existsSync(path.join(CACHE, '.git'))) return;
  await fsp.mkdir(path.dirname(CACHE), { recursive: true });
  execFileSync('git', ['clone', '--depth', '1', REPO, CACHE], { stdio: 'inherit' });
}

async function apply() {
  const list = await files();
  await fsp.rm(TARGET, { recursive: true, force: true });
  for (const [rel, source] of list) {
    const target = path.join(TARGET, rel);
    await fsp.mkdir(path.dirname(target), { recursive: true });
    await fsp.copyFile(source, target);
  }
  console.log(`vendor: ${list.length} files copied to static/assets/lib (${PIN.slice(0, 7)})`);
}

async function generate() {
  const list = await files();
  const manifest = {
    repo: REPO,
    pin: PIN,
    note: 'Vendored browser libraries; MathJax and Mermaid stay on the CDN. Generated by scripts/vendor.mjs.',
    files: Object.fromEntries(
      await Promise.all(
        list.map(async ([rel, source]) => [rel, sha256(await fsp.readFile(source))]),
      ),
    ),
  };
  await fsp.writeFile(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`vendor: manifest written (${list.length} files)`);
}

async function check() {
  const manifest = JSON.parse(await fsp.readFile(MANIFEST, 'utf8'));
  if (manifest.pin !== PIN) {
    console.error(`FAIL pin: manifest ${manifest.pin}, script ${PIN}`);
    process.exit(1);
  }
  let failures = 0;
  for (const [rel, digest] of Object.entries(manifest.files)) {
    const target = path.join(TARGET, rel);
    if (!fs.existsSync(target)) {
      console.error(`FAIL missing static/assets/lib/${rel}`);
      failures += 1;
      continue;
    }
    if (sha256(await fsp.readFile(target)) !== digest) {
      console.error(`FAIL drifted static/assets/lib/${rel}`);
      failures += 1;
    }
  }
  if (failures) process.exit(1);
  console.log(`vendor: ${Object.keys(manifest.files).length} files match the pin (${PIN.slice(0, 7)})`);
}

const argv = new Set(process.argv.slice(2));
if (argv.has('--fetch')) await fetchUpstream();
else if (argv.has('--apply')) await apply();
else if (argv.has('--generate')) await generate();
else if (argv.has('--check')) await check();
else {
  console.error('usage: node scripts/vendor.mjs --fetch | --apply | --generate | --check');
  process.exit(2);
}

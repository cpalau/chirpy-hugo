#!/usr/bin/env node
/**
 * Generate and verify the translation catalogue.
 *
 *   node scripts/i18n.mjs --apply    # upstream locales -> i18n/
 *   node scripts/i18n.mjs --check    # regenerate in memory and compare
 *
 * The upstream catalogue (`_data/locales/*.yml`) is the source, but it is not
 * uniform: some locales are missing `df.*` date formats and some write
 * `categories.category_measure` as a string instead of a `{singular, plural}`
 * map. Hugo silently falls back to English for the first case and renders an
 * empty string for the second, so the generated catalogue is normalised against
 * `en.yml`: every locale ends with exactly the same key tree, and a missing
 * translation falls back to the English value instead of disappearing.
 *
 * The only name transformation: two locales use U+2011 (a non-breaking hyphen)
 * in their file name, which Hugo rejects as a language tag, so it becomes an
 * ASCII hyphen (G-25).
 *
 * `--check` regenerates the catalogue from the pinned upstream copy and fails
 * if the committed files differ by a single byte, so the generator and the
 * repository cannot drift.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { parse, stringify } from 'yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const I18N = path.join(ROOT, 'i18n');
const CACHE = path.join(ROOT, '.out/upstream');
const REFERENCE = 'en.yml';
const NB_HYPHEN = '\u2011';
const HEADER = `# Generated by scripts/i18n.mjs from the pinned upstream locale.
# Do not edit: run \`npm run i18n\` instead. Missing translations fall back to
# English, so every key is present in every locale.
`;

async function upstreamDir() {
  const entries = await fs.readdir(CACHE, { withFileTypes: true }).catch(() => []);
  for (const entry of entries.filter((e) => e.isDirectory())) {
    for (const inner of ['gem', 'tag']) {
      const candidate = path.join(CACHE, entry.name, inner, '_data/locales');
      try {
        await fs.access(candidate);
        return candidate;
      } catch {
        // try the next candidate
      }
    }
  }
  throw new Error(
    `no upstream locales in ${CACHE}: run "node scripts/fetch-upstream.mjs --fetch" first`,
  );
}

function targetName(name) {
  return name.replaceAll(NB_HYPHEN, '-');
}

const isMap = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);

/**
 * Rebuild `value` with the shape of `reference`.
 *
 * A missing key takes the reference value. A scalar where the reference has a
 * `{singular, plural}` map is expanded to both forms, which is the shape
 * upstream templates read (`.plural | default: <string>`). Keys the reference
 * does not have are dropped: no template can reach them.
 */
function normalize(reference, value, filled) {
  if (!isMap(reference)) return value ?? reference;
  const out = {};
  const source = isMap(value) ? value : {};
  for (const [key, ref] of Object.entries(reference)) {
    if (isMap(ref) && typeof source[key] === 'string' && 'singular' in ref) {
      out[key] = { singular: source[key], plural: source[key] };
      continue;
    }
    if (!(key in source)) {
      filled.add(key);
      out[key] = structuredClone(ref);
      continue;
    }
    out[key] = normalize(ref, source[key], filled);
  }
  return out;
}

async function render() {
  const source = await upstreamDir();
  const files = (await fs.readdir(source)).filter((f) => f.endsWith('.yml')).sort();
  const reference = parse(await fs.readFile(path.join(source, REFERENCE), 'utf8'));
  const output = new Map();

  for (const file of files) {
    const data = parse(await fs.readFile(path.join(source, file), 'utf8')) ?? {};
    const filled = new Set();
    const normalized = normalize(reference, data, filled);
    output.set(
      targetName(file),
      HEADER + stringify(normalized, { lineWidth: 0, defaultStringType: 'QUOTE_DOUBLE', defaultKeyType: 'PLAIN' }),
    );
  }
  return output;
}

async function apply() {
  const catalog = await render();
  await fs.mkdir(I18N, { recursive: true });
  for (const [file, content] of catalog) {
    await fs.writeFile(path.join(I18N, file), content);
  }
  for (const file of await fs.readdir(I18N)) {
    if (file.endsWith('.yml') && !catalog.has(file)) await fs.rm(path.join(I18N, file));
  }
  console.log(`i18n: ${catalog.size} locales written`);
}

async function check() {
  const catalog = await render();
  const local = (await fs.readdir(I18N)).filter((f) => f.endsWith('.yml')).sort();
  const problems = [];

  for (const file of catalog.keys()) {
    if (!local.includes(file)) problems.push(`missing i18n/${file}`);
  }
  for (const file of local) {
    if (!catalog.has(file)) problems.push(`unexpected i18n/${file}`);
  }
  for (const [file, expected] of catalog) {
    if (!local.includes(file)) continue;
    const actual = await fs.readFile(path.join(I18N, file), 'utf8');
    if (actual !== expected) problems.push(`drifted i18n/${file} (run "npm run i18n")`);
  }

  if (problems.length) {
    for (const problem of problems.slice(0, 20)) console.error(`  ${problem}`);
    if (problems.length > 20) console.error(`  … ${problems.length - 20} more`);
    console.error(`i18n: ${problems.length} problem(s)`);
    process.exit(1);
  }
  console.log(`i18n: ${local.length} locales, identical key trees, no empty values`);
}

if (process.argv.includes('--apply')) await apply();
else if (process.argv.includes('--check')) await check();
else {
  console.error('usage: node scripts/i18n.mjs --apply | --check');
  process.exit(2);
}
